package dev.lelonio.square.airpods.runtime.media

import dev.lelonio.square.airpods.runtime.AirPodsMediaGesture
import dev.lelonio.square.airpods.runtime.automation.*
import dev.lelonio.square.airpods.runtime.storage.PairAddress
import java.io.Closeable

/** Optional root-owned bridge into an ALREADY running player; never bind/start playback.
 * read must use the actual AudioRouting routed device of the active output, match its Bluetooth
 * address against pair, reject Connect/remote output and refresh mediaAccountEpoch before returning.
 * Unknown route is false. sessionGeneration changes on player/session replacement.
 * Origin receipts require an applied local command plus no intervening manual/app/focus override.
 * Manual PAUSE even when already paused increments transportRevision; volume changes from any
 * other owner increment volumeRevision. Receipts must not be generated by generic callbacks.
 * foreignDuckActive includes AudioFocus attenuation; unknown ownership must return true.
 */
interface LocalAirPodsMediaBridge {
    fun read(pair: PairAddress): MediaCandidate?
    fun observe(changed: () -> Unit): Closeable
    fun execute(target: MediaTarget, action: MediaAction, value: Int?, effectId: Long?): Boolean
    fun gesture(target: MediaTarget, action: AirPodsMediaGesture): Boolean
}
