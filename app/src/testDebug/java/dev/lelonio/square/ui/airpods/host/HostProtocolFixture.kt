/** The only replaced production method is the Bluetooth transport factory, before JNI.
 * Custom-class instrumentation is required by the @Config on BOTH test classes.
 * A missing fixture fails closed; it must never fall through to native Bluetooth. */
@Implements(value = AirPodsSocket::class, isInAndroidSdk = false)
class HostProtocolSocketShadow {
    @Implementation
    protected fun create(adapter: BluetoothAdapter, device: BluetoothDevice): AacpTransport {
        calls.incrementAndGet()
        check(device.address == HostProtocolFixture.PAIR.value)
        return checkNotNull(next.getAndSet(null)) { "No synthetic AACP transport installed" }
    }

    companion object {
        internal val next = AtomicReference<HostProtocolTransport?>()
        internal val calls = AtomicInteger()
        @JvmStatic @Resetter fun reset() { next.getAndSet(null)?.close(); calls.set(0) }
    }
}

/** Real writer/read-loop run on IO. The fake only records complete SDUs and supplies RX.
 * A barrier is INSIDE raw.write: the first packet has already reached transport; a second
 * property waits behind the production writer mutex and must be reauthorized when drained. */
internal class HostProtocolTransport : AacpTransport {
    class Barrier(val hex: String) {
        val entered = CountDownLatch(1)
        val release = CountDownLatch(1)
    }
    val writes = CopyOnWriteArrayList<List<Byte>>()
    val connects = AtomicInteger()
    val readsStarted = AtomicInteger()
    val readsReturned = AtomicInteger()
    private val incoming = LinkedBlockingQueue<ByteArray>()
    @Volatile var barrier: Barrier? = null
    @Volatile var lateOnClose: String? = null
    @Volatile var lateReadBarrier: Barrier? = null
    @Volatile var closed = false
        private set

    override fun connect() { check(!closed); connects.incrementAndGet() }
    override fun readSdu(): ByteArray? {
        readsStarted.incrementAndGet()
        val packet = incoming.take()
        if (closed && packet.isNotEmpty()) lateReadBarrier?.let {
            it.entered.countDown()
            check(it.release.await(4, TimeUnit.SECONDS)) { "Late test RX was not released" }
        }
        readsReturned.incrementAndGet()
        return packet.takeIf { it.isNotEmpty() }
    }
    override fun write(packet: ByteArray) {
        check(!closed)
        writes.add(packet.toList())
        barrier?.takeIf { packet.contentEquals(HostProtocolWire.bytes(it.hex)) }?.let {
            it.entered.countDown()
            check(it.release.await(4, TimeUnit.SECONDS)) { "Test transport barrier was not released" }
        }
    }
    fun deliver(hex: String) { check(!closed); incoming.put(HostProtocolWire.bytes(hex)) }
    fun count(hex: String) = writes.count { it == HostProtocolWire.bytes(hex).toList() }
    override fun close() {
        if (!closed) {
            closed = true
            incoming.offer(lateOnClose?.let(HostProtocolWire::bytes) ?: byteArrayOf())
        }
        barrier?.release?.countDown()
    }
}

/** PREPARED ONLY. Real host/controller/C4/store/lease/service/repository/codec, fake Bluetooth,
 * SDUs and persistence, Robolectric Android. No reflected ticket, runtime state or repository.
 * The real finite FUNCTIONAL_TEST permit and UI authority keep productConformance FALSE.
 * This does not exercise debug qualification, resolver publication, background or hardware. */
internal class HostProtocolFixture : AutoCloseable {
    companion object { val PAIR = PairAddress("02:00:00:00:00:51") }
    val context: Application = RuntimeEnvironment.getApplication()
    val visible = MutableStateFlow(true)
    @Volatile var ingressCurrent = true
    @Volatile var bluetoothPermission = true
    private val adapter = context.getSystemService(BluetoothManager::class.java).adapter
    private val device = adapter.getRemoteDevice(PAIR.value)
    val facts = object : BluetoothRuntimeFacts {
        override val adapter: BluetoothAdapter = this@HostProtocolFixture.adapter
        override fun permitted() = bluetoothPermission
        override fun bond(address: PairAddress) = BondFact.BONDED
        override fun connection(address: PairAddress) = ProfileConnection.CONNECTED
        override fun prepare() = Unit
        override fun whenProfileReady(ready: () -> Unit): AutoCloseable? = null
        override fun audioSettingsIntent() = Intent()
    }
    private val persistence = object : RuntimePersistence {
        private var data: ByteArray? = null
        @Synchronized override fun read() = data?.clone()
        @Synchronized override fun commit(bytes: ByteArray): Boolean { data = bytes.clone(); return true }
    }
    val permit = AirPodsFunctionalTestPermit.issue(SystemClock::elapsedRealtime)
    val events = CopyOnWriteArrayList<QualificationEvent>()
    val transport = HostProtocolTransport()
    val owner: AirPodsAndroidController
    val host: AirPodsHost
    private val service = Robolectric.buildService(AirPodsControlService::class.java)
    private var serviceCreated = false

    init {
        // Custom-shadow companion fields survive sandbox resets. Reset only observation counts,
        // after proving the previous fixture left neither an owner nor a pending transport.
        check(AirPodsServiceOwnerRegistry.resolve() == null)
        check(HostProtocolSocketShadow.next.get() == null)
        HostProtocolSocketShadow.calls.set(0)
        ShadowProcess.setPid(41951)
        shadowOf(context).grantPermissions(Manifest.permission.BLUETOOTH_CONNECT, Manifest.permission.POST_NOTIFICATIONS)
        shadowOf(adapter).setState(BluetoothAdapter.STATE_ON)
        shadowOf(device).setBondState(BluetoothDevice.BOND_BONDED)
        owner = AirPodsAndroidController(context, visible, { false }, null,
            testPermit = permit, scratchStore = AirPodsRuntimeStore(persistence),
            factsOverride = facts, observer = AirPodsQualificationObserver { events.add(it) })
        host = AirPodsHost(context, owner,
            functionalAuthority = AirPodsFunctionalUiAuthority(owner) { ingressCurrent },
            ingressCurrent = { ingressCurrent })
        installHostBluetooth(host)
    }

    fun installHostBluetooth(target: AirPodsHost) {
        val bluetooth = ReflectionHelpers.getField<HostBluetooth>(target, "bluetooth")
        val profile = Proxy.newProxyInstance(BluetoothProfile::class.java.classLoader,
            arrayOf(BluetoothProfile::class.java)) { proxy, method, args ->
            when (method.name) {
                "getConnectedDevices" -> listOf(device)
                "getConnectionState" -> BluetoothProfile.STATE_CONNECTED
                "getDevicesMatchingConnectionStates" -> listOf(device)
                "hashCode" -> System.identityHashCode(proxy)
                "equals" -> proxy === args?.firstOrNull()
                "toString" -> "Synthetic A2DP profile"
                else -> null
            }
        } as BluetoothProfile
        // Existing HostFacade/StemHost convention; reflection restricted to Bluetooth facts.
        ReflectionHelpers.setField(bluetooth, "profile", profile)
        ReflectionHelpers.setField(bluetooth, "requested", true)
    }

    fun detachHostBluetooth(target: AirPodsHost) {
        // A dynamic BluetoothProfile has no Android proxy resource to close.
        ReflectionHelpers.setField(ReflectionHelpers.getField<HostBluetooth>(target, "bluetooth"), "profile", null)
    }

    fun revokeBluetoothPermission() {
        bluetoothPermission = false
        shadowOf(context).denyPermissions(Manifest.permission.BLUETOOTH_CONNECT)
    }

    fun start() {
        runBlocking {
            owner.selectPair(PAIR).getOrThrow()
            assertTrue(owner.beginFunctionalTest() is GateResult.Started)
        }
        assertTrue(owner.hasAdmission())
        assertSame(owner, AirPodsServiceOwnerRegistry.resolve())
        assertEquals(0, HostProtocolSocketShadow.calls.get())
        assertNull(owner.store.snapshot().getOrThrow().pairs.getValue(PAIR).verification)
        assertTrue(HostProtocolSocketShadow.next.compareAndSet(null, transport))
        service.create(); serviceCreated = true
        service.get().onStartCommand(Intent(context, AirPodsControlService::class.java), 0, 1)
        await("automatic bootstrap") { owner.state.value.stage == AacpStage.SUBSCRIBED }
        assertEquals(1, HostProtocolSocketShadow.calls.get())
        assertEquals(1, transport.connects.get())
        assertEquals(listOf(
            HostProtocolWire.bytes(HostProtocolWire.HANDSHAKE).toList(),
            HostProtocolWire.bytes(HostProtocolWire.FEATURE_FLAGS).toList(),
            HostProtocolWire.bytes(HostProtocolWire.SUBSCRIBE).toList(),
            HostProtocolWire.bytes(HostProtocolWire.BOOTSTRAP_EXTENSION).toList()), transport.writes.toList())
        refresh()
        assertFalse("Subscribed without current RX is not setup", host.state.value.controlsReady)
        write(CommandProperty.MIC_MODE, PropertyValue.Number(2))
        assertEquals(0, transport.count(HostProtocolWire.MIC_LEFT))
        transport.deliver(HostProtocolWire.INFORMATION)
        await("INFORMATION decoded without basic RX") { owner.state.value.identityReceived != null }
        refresh()
        assertFalse("INFORMATION alone is not setup", host.state.value.controlsReady)
        transport.deliver(HostProtocolWire.MIC_AUTO)
        transport.deliver(HostProtocolWire.MODE_TRANSPARENCY)
        await("decoded current setup") { owner.functionalUiAuthorized() &&
            owner.state.value.mode?.value == ListeningMode.TRANSPARENCY }
        refresh()
        assertTrue(host.state.value.controlsReady)
        assertFalse(host.state.value.productGatePassed)
        assertFalse(owner.runtime.value.productConformance)
        assertNull(owner.store.snapshot().getOrThrow().pairs.getValue(PAIR).verification)
    }

    fun refresh() = runBlocking { host.refresh() }
    fun write(property: CommandProperty, value: PropertyValue, stamp: HostStamp? = host.stamp,
        generation: Long = owner.state.value.generation) = runBlocking {
        host.dispatch(stamp, AirPodsUiAction.Write(generation, property, value)) { _, _ ->
            fail("Protocol action must not launch platform UI")
        }
    }
    fun observed(property: CommandProperty) = owner.state.value.propertyObserved(property)?.value
    fun receive(hex: String, property: CommandProperty, value: PropertyValue) {
        transport.deliver(hex)
        await("decoded $property") { observed(property) == value && property !in owner.state.value.pending }
        refresh()
    }
    fun await(description: String, timeoutMs: Long = 4_000, condition: () -> Boolean) {
        val end = System.nanoTime() + TimeUnit.MILLISECONDS.toNanos(timeoutMs)
        while (!condition() && System.nanoTime() < end) {
            shadowOf(Looper.getMainLooper()).idle()
            Thread.sleep(2)
        }
        assertTrue("Timed out: $description; stage=${owner.state.value.stage}", condition())
    }
    fun text(resource: Int) = context.getString(resource)

    override fun close() {
        transport.barrier?.release?.countDown()
        transport.lateReadBarrier?.release?.countDown()
        try {
            runBlocking { owner.stopControls() }
            if (serviceCreated) service.destroy()
            shadowOf(Looper.getMainLooper()).idle()
            // close() interrupts a real IO worker; permit disposal retries explicit cleanup once
            // after the read returns, rather than editing registry/lease ownership reflectively.
            await("transport read released") { !serviceCreated || transport.closed }
            runBlocking { owner.disposeFunctionalTest() }
            await("process lease released") {
                val probe = AirPodsTransportOwnership.process.reserve(AirPodsTransportOwnership.Owner.DIAGNOSTIC)
                if (probe == null) false else { probe.close(); true }
            }
        } finally {
            detachHostBluetooth(host)
            host.close()
            transport.close()
            HostProtocolSocketShadow.next.compareAndSet(transport, null)
        }
    }
}
